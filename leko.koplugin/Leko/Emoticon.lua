-- 未收录的码：只记一次，避免翻页/重开弹窗刷屏
local _unknown_seen = {}

local function note_unknown(name)
    if _unknown_seen[name] then return end
    _unknown_seen[name] = true
    local ok, L = pcall(require, "logger")
    if ok and type(L) == "table" and L.info then
        pcall(L.info, "[leko emoticon] 未收录的段评表情码: [" .. name .. "]")
    end
end

--- 判断方括号内容是否像番茄汉字码（过滤 URL / Markdown 链接等噪声）。
--- 表情码 = 1~8 个汉字、字母或数字，不含空白与 / . : 等路径字符。
local function is_code_like(name)
    if type(name) ~= "string" then return false end
    local len = #name
    if len < 1 or len > 24 then return false end -- ≤8 个汉字
    if name:find("[%s/%.%:%?%#%&%=%%]") then return false end
    return true
end

--- 把文本里的表情码替换成 emoji：
---   * QQ 阅读：`[emot=default,21/]` → 按经典 QQ 表情编号查表；未收录的 id 直接吞掉。
---   * 七猫「小七猫」：`[小七_笑哭]` → 剥掉 `小七_` 前缀后查 MAP；未收录的剥前缀保留。
---   * 番茄 / 七猫「小黄豆」：`[奸笑]` 这种汉字码 → 查 MAP；未收录的原样保留。
function Emoticon.decode(s)
    if type(s) ~= "string" or s == "" then return s end
    -- QQ 阅读段评表情码（先做，避免被下面的汉字码规则当成普通方括号）
    if s:find("emot=", 1, true) then
        s = s:gsub("%[emot=[%w_]+,(%d+)/%]", function(id)
            local emoji = QQ_EMOT[tonumber(id)]
            if emoji then return emoji end
            note_unknown("emot:" .. id)
            return "" -- 未收录：吞掉，不把 [emot=...] 留给读者
        end)
    end
    -- 七猫「小七猫」家族：`[小七_XXX]`。前缀只是命名空间，剥掉再查 MAP；
    -- 未收录的也剥前缀（`[小七_神评]`→`[神评]`），不把 `小七_` 噪声留给读者。
    if s:find("小七_", 1, true) then
        s = s:gsub("%[小七_([^%[%]\r\n]-)%]", function(name)
            local emoji = MAP[name]
            if emoji then return emoji end
            note_unknown("小七:" .. name)
            return "[" .. name .. "]"
        end)
    end
    if not s:find("[", 1, true) then return s end
    local out = s:gsub("%[([^%[%]\r\n]*)%]", function(name)
        if not is_code_like(name) then return "[" .. name .. "]" end
        local emoji = MAP[name]
        if emoji then return emoji end
        note_unknown(name)
        return "[" .. name .. "]"
    end)
    return out
end

--- 已收录的码数量（冒烟/诊断用）
function Emoticon.size()
    local n, q = 0, 0
    for _ in pairs(MAP) do n = n + 1 end
    for _ in pairs(QQ_EMOT) do q = q + 1 end
    return n, q
end

return Emoticon
